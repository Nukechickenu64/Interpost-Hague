#!/usr/bin/env python3
"""Scrape the Lexaloffle BBS featured PICO-8 cart listing and bake it into
code/game/machinery/tbox_bbs_carts.dm as the tbox_bbs_cart_library global.

The T-box "BBS cartridge" spawns as a random entry from this list and plays
through Lexaloffle's official embeddable widget player (widget.php), so no
cart content is redistributed with the game.

Run: python tools/fetch_bbs_top_carts.py [pages]
Rerun whenever you want to refresh the list (default 4 pages ~= top 100).
"""
import os
import re
import sys
import time
import urllib.request

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
OUT = os.path.join(ROOT, "code", "game", "machinery", "tbox_bbs_carts.dm")

LISTER = ("https://www.lexaloffle.com/bbs/lister.php"
          "?cat=7&sub=2&mode=carts&orderby=featured&page=%d")

# pdat_<pid> blocks each contain the thread link and title div.
ENTRY_RE = re.compile(
    r'id="pdat_(\d+)".*?<a href="\?tid=\d+">.*?margin:auto">([^<]+)</div>',
    re.S)


def fetch(url):
    req = urllib.request.Request(url, headers={"User-Agent": "tbox-cart-list/1.0"})
    with urllib.request.urlopen(req, timeout=30) as resp:
        return resp.read().decode("utf-8", "replace")


def clean_title(title):
    title = re.sub(r"\s+", " ", title).strip()
    # Keep DM string literals trivially safe: printable ASCII only.
    title = "".join(ch for ch in title if 32 <= ord(ch) < 127)
    title = title.replace("\\", "").replace('"', "'").replace("[", "(").replace("]", ")")
    return title[:64] if title else "Untitled"


def main():
    pages = int(sys.argv[1]) if len(sys.argv) > 1 else 4
    carts = []
    seen = set()
    for page in range(1, pages + 1):
        html = fetch(LISTER % page)
        found = ENTRY_RE.findall(html)
        if not found:
            print("page %d: no entries found, stopping" % page)
            break
        for pid, title in found:
            if pid in seen:
                continue
            seen.add(pid)
            carts.append((int(pid), clean_title(title)))
        print("page %d: %d entries (%d total)" % (page, len(found), len(carts)))
        time.sleep(1)

    if not carts:
        raise SystemExit("no carts scraped; BBS layout may have changed")

    lines = [
        "// AUTOGENERATED by tools/fetch_bbs_top_carts.py - do not edit by hand.",
        "// Featured PICO-8 carts from the Lexaloffle BBS, played via the official",
        "// embeddable widget player (nothing is redistributed with the game).",
        "// Scraped %s. Rerun the script to refresh." % time.strftime("%Y-%m-%d"),
        "var/global/list/tbox_bbs_cart_library = list(",
    ]
    for pid, title in carts:
        lines.append('\t"%d" = "%s",' % (pid, title))
    lines.append(")")
    lines.append("")

    with open(OUT, "w", newline="\n") as f:
        f.write("\n".join(lines))
    print("wrote %s (%d carts)" % (OUT, len(carts)))


if __name__ == "__main__":
    main()
